export const getRandomElement = (category: string): string => {
  const categoryData = characterElements.find(el => el.category === category);
  if (!categoryData) return "";
  
  const randomIndex = Math.floor(Math.random() * categoryData.items.length);
  return categoryData.items[randomIndex];
};

export const getRandomElements = (count: number = 1): string[] => {
  const availableCategories = characterElements.map(el => el.category);
  const selectedCategories = [];
  
  // 确保包含基础元素
  const essentialCategories = ["基础外貌", "服装风格", "场景环境", "艺术风格"];
  essentialCategories.forEach(category => {
    if (availableCategories.includes(category)) {
      selectedCategories.push(category);
    }
  });
  
  // 随机添加其他元素
  const remainingCategories = availableCategories.filter(cat => !essentialCategories.includes(cat));
  const additionalCount = Math.min(count - selectedCategories.length, remainingCategories.length);
  
  for (let i = 0; i < additionalCount; i++) {
    const randomIndex = Math.floor(Math.random() * remainingCategories.length);
    const selectedCategory = remainingCategories.splice(randomIndex, 1)[0];
    selectedCategories.push(selectedCategory);
  }
  
  return selectedCategories.map(category => getRandomElement(category));
};
